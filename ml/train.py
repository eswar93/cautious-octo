"""Train baseline logistic model and export it as C for the Nucleo.

    python ml/train.py            # writes core/model_weights.hpp and core/test/golden.hpp

Feature definitions live in features.py and core/window.hpp; keep them in sync. The golden
vector lets core/test/test_core.c prove the C code matches Python.
"""
import pathlib
import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import precision_score, recall_score, confusion_matrix

from features import make_windows, window_features, NFEAT
import synth

ROOT = pathlib.Path(__file__).resolve().parents[1]
RATE_HZ, N, HORIZON_S = 10, 32, 2.0   # window = N samples @ RATE_HZ


def main():
    t, v, y_s = synth.generate(duration_s=3600, rate_hz=RATE_HZ, seed=1, horizon_s=HORIZON_S)
    X, y = make_windows(t, v, y_s, N)
    split = int(0.7 * len(X))                     # split by TIME, never shuffle windows
    Xtr, ytr, Xte, yte = X[:split], y[:split], X[split:], y[split:]

    mu, sd = Xtr.mean(0), Xtr.std(0)
    sd[sd < 1e-9] = 1.0
    clf = LogisticRegression(class_weight="balanced", max_iter=1000)
    clf.fit((Xtr - mu) / sd, ytr)

    thr = 0.7
    p = clf.predict_proba((Xte - mu) / sd)[:, 1]
    pred = (p > thr).astype(int)
    print("test windows:", len(yte), " positives:", int(yte.sum()))
    print("precision: %.3f  recall: %.3f" % (precision_score(yte, pred), recall_score(yte, pred)))
    print("confusion [[TN FP][FN TP]]:\n", confusion_matrix(yte, pred))

    def arr(a): return ", ".join("%.8ff" % x for x in a)
    (ROOT / "core" / "model_weights.hpp").write_text(f"""// GENERATED by ml/train.py -- do not edit
#pragma once
#include "predictor.hpp"

namespace tp {{
inline constexpr Model kModel{{
    .mu = {{{{ {arr(mu)} }}}},
    .sd = {{{{ {arr(sd)} }}}},
    .w = {{{{ {arr(clf.coef_[0])} }}}},
    .b = {clf.intercept_[0]:.8f}f,
    .threshold = {thr}f,
    .window_n = {N},
}};
}}  // namespace tp
""")

    # golden vector: one late window with its expected probability
    i = len(v) - 1 - 50
    tw, vw = t[i - N + 1: i + 1], v[i - N + 1: i + 1]
    f = window_features(tw, vw)
    pg = clf.predict_proba(((f - mu) / sd).reshape(1, -1))[0, 1]
    ts = ", ".join(str(int(round(x * 1000))) for x in tw)
    (ROOT / "core" / "test" / "golden.hpp").write_text(f"""// GENERATED by ml/train.py -- do not edit
#pragma once
#include <array>
#include <cstddef>
#include <cstdint>

inline constexpr std::size_t kGoldenN = {N};
inline constexpr std::array<std::uint32_t, kGoldenN> kGoldenT{{{{ {ts} }}}};
inline constexpr std::array<float, kGoldenN> kGoldenV{{{{ {arr(vw)} }}}};
inline constexpr float kGoldenP = {pg:.8f}f;
""")
    print("wrote core/model_weights.hpp and core/test/golden.hpp")


if __name__ == "__main__":
    main()
